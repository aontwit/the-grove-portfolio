/** "ห้องนอน 2 กับห้องนอนใหญ่" — ไทยไม่เว้นวรรคระหว่างคำ แต่ชื่อที่จบด้วยตัวเลขต้องเว้นก่อน "กับ"
    data ตั้งชื่อห้องสั้น ("นอน 2", "ครัว") ยกเว้นที่มีคำว่าห้องอยู่แล้ว ("ห้องพระ") */
function joinRoomsTh(names: readonly string[]) {
  return names
    .map((n) => (n.startsWith("ห้อง") ? n : `ห้อง${n}`))
    .reduce((acc, n, i) => (i === 0 ? n : `${acc}${/\d$/.test(acc) ? " " : ""}กับ${n}`), "");
}

/** จำนวนแปลงแยกตามสถานะ — ประโยคที่บอกสถานะทั้งผังรับก้อนนี้ */
export type StatusCounts = {
  available: number;
  unconfirmed: number;
  reserved: number;
  sold: number;
};

/** "ว่าง 2 · รอยืนยันสถานะ 18 · ขายแล้ว 4" — บอกเฉพาะสถานะที่มีแปลงอยู่จริง */
function countsTh(c: StatusCounts) {
  return (
    [
      [c.available, "ว่าง"],
      [c.unconfirmed, "รอยืนยันสถานะ"],
      [c.reserved, "จอง"],
      [c.sold, "ขายแล้ว"],
    ] as const
  )
    .filter(([n]) => n > 0)
    .map(([n, w]) => `${w} ${n}`)
    .join(" · ");
}

